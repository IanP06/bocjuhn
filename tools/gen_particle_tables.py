"""Regenerate compact dry-particle lookup tables (no target floating point)."""
from pathlib import Path
import math
probability=[]; gain=[]
for i in range(129):
    t=i/128
    d=(261.6255653005986*2**(6*t*t)/48000)**2/6
    probability.append(round(d*48000/44100*2**32))
    gain.append(round(.5*d**(-.25)*65536))
p=Path(__file__).resolve().parents[1]/'firmware/src/particle_tables.h'
p.write_text('/* Generated by tools/gen_particle_tables.py; reference density at 48 kHz, event rate retained at 44.1 kHz. */\n'+''.join('static const uint32_t '+n+'[129] = {\n'+',\n'.join('    '+', '.join(map(str,v[j:j+8])) for j in range(0,129,8))+'\n};\n' for n,v in [('DP_DENSITY',probability),('DP_PRE',gain)]),newline='\n')
