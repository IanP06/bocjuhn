"""Reproducible constants for FRACT DATA, all rates based on 44100 Hz."""
import math
from pathlib import Path
root=Path(__file__).resolve().parents[1]
specs=[('FD_FREQ8','uint32_t',[round(256*20*900**(i/128)) for i in range(129)]),
       ('FD_SUB8','uint32_t',[round(256*20*9**(i/128)) for i in range(129)]),
       ('FD_PERIOD','uint32_t',[round(44100/(0.5*256**(i/128))) for i in range(129)]),
       ('FD_LENGTH','uint16_t',[round(11*1000**(i/128)) for i in range(129)])]
s='/* Generated by tools/gen_fract_data.py. SPDX-License-Identifier: GPL-3.0-only */\n'
for name,typ,values in specs:
    s+=f'static const {typ} {name}[129] = {{\n'
    for n in range(0,len(values),12):s+='    '+','.join(map(str,values[n:n+12]))+',\n'
    s+='};\n'
(root/'firmware/src/fract_data_tables.h').write_text(s)
